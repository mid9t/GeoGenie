"""
Patch README.md benchmark tables from harness JSON artifacts.

Markers:
  <!-- BENCH_TABLE:BEGIN ... --> ... <!-- BENCH_TABLE:END -->
  <!-- METRICS_TABLE:BEGIN ... --> ... <!-- METRICS_TABLE:END -->

--check exits nonzero if generated blocks would differ (CI drift gate).
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Any, Dict, Optional, Tuple

ROOT = Path(__file__).resolve().parents[2]
README = ROOT / "README.md"
RESULTS = ROOT / "eval" / "results"


def _fmt_us(row: Optional[Dict[str, Any]]) -> str:
    if not row:
        return "—"
    med = row["query_us_per_query"]["median"]
    q1, q3 = row["query_us_per_query"]["iqr"]
    return f"{med:.2f} ({q1:.2f}–{q3:.2f})"


def build_bench_table(index_compare: Dict[str, Any]) -> str:
    by_n: Dict[int, Dict[str, Dict]] = {}
    for row in index_compare["results"]:
        by_n.setdefault(row["n"], {})[row["index"]] = row
    lines = [
        "| Dataset size | Brute-force (µs/q) | k-d tree (µs/q) | R-tree (µs/q) | Speedup (best vs brute) |",
        "|---|---|---|---|---|",
    ]
    for n in sorted(by_n):
        cells = by_n[n]
        brute = cells.get("brute_force")
        kd = cells.get("kdtree")
        rt = cells.get("rtree")
        brute_med = brute["query_us_per_query"]["median"] if brute else None
        best = None
        for name in ("kdtree", "rtree"):
            if name in cells and brute_med:
                sp = brute_med / max(cells[name]["query_us_per_query"]["median"], 1e-12)
                best = sp if best is None else max(best, sp)
        lines.append(
            f"| {n:,} | {_fmt_us(brute)} | {_fmt_us(kd)} | {_fmt_us(rt)} | "
            f"{f'{best:.1f}×' if best else '—'} |"
        )
    cfg = index_compare.get("config", {})
    env = index_compare.get("env", {})
    footnote = (
        f"*Index stage only — median (IQR) µs/query; "
        f"{cfg.get('reps', '?')} reps × {cfg.get('queries', '?')} queries, "
        f"warmup {cfg.get('warmup', '?')}, seed {cfg.get('seed', '?')}, "
        f"radius {cfg.get('radius_m', '?')} m. "
        f"Env: Python {env.get('python')}, {env.get('platform')}, "
        f"{env.get('cpu_count')} CPUs, git {env.get('git_sha')}, {env.get('timestamp')}. "
        f"Brute-force baseline is vectorized NumPy, not a Python loop.*"
    )
    return "\n".join(lines) + "\n\n" + footnote


def build_metrics_table(e2e: Dict[str, Any], parser: Dict[str, Any]) -> str:
    mode = e2e.get("mode", "?")
    cold = e2e.get("cold", {})
    warm = e2e.get("warm", {})
    full = parser.get("full_query_accuracy")
    per = parser.get("per_field_accuracy", {})
    lines = [
        "| Metric | Value |",
        "|---|---|",
        f"| LLM query-parsing accuracy (hand-labeled, full-query) | "
        f"{full * 100:.1f}% (n={parser.get('n', '?')}) |"
        if full is not None
        else "| LLM query-parsing accuracy (hand-labeled, full-query) | — |",
        f"| Per-field parser accuracy (radius / filters / sort) | "
        f"{per.get('radius', 0) * 100:.0f}% / {per.get('filters', 0) * 100:.0f}% / "
        f"{per.get('sort', 0) * 100:.0f}% |",
        f"| End-to-end reachability latency cold p50 / p95 ({mode}) | "
        f"{cold.get('p50_ms', float('nan')):.2f} / {cold.get('p95_ms', float('nan')):.2f} ms |",
        f"| End-to-end reachability latency warm p50 / p95 ({mode}) | "
        f"{warm.get('p50_ms', float('nan')):.2f} / {warm.get('p95_ms', float('nan')):.2f} ms |",
    ]
    wl = e2e.get("workload", {})
    env = e2e.get("env", {})
    footnote = (
        f"*E2E mode={mode}; workload: {wl.get('requests')} requests over "
        f"{wl.get('origins_pool')} Zipf({wl.get('zipf')}) origins, "
        f"{wl.get('minutes')} min walk. LLM parse excluded from e2e "
        f"(see parser rows / `parser_eval.py`). "
        f"Env: Python {env.get('python')}, git {env.get('git_sha')}, {env.get('timestamp')}.*"
    )
    return "\n".join(lines) + "\n\n" + footnote


def _replace_block(text: str, begin: str, end: str, body: str) -> str:
    pattern = re.compile(
        re.escape(begin) + r".*?" + re.escape(end),
        re.DOTALL,
    )
    replacement = f"{begin}\n{body}\n{end}"
    if not pattern.search(text):
        raise RuntimeError(f"markers not found: {begin} … {end}")
    return pattern.sub(replacement, text, count=1)


def generate(readme_text: str, results_dir: Path) -> str:
    index_compare = json.loads((results_dir / "index_compare.json").read_text())
    e2e = json.loads((results_dir / "e2e.json").read_text())
    parser = json.loads((results_dir / "parser_eval.json").read_text())
    text = _replace_block(
        readme_text,
        "<!-- BENCH_TABLE:BEGIN (autogenerated by eval/emit_readme_tables.py — do not hand-edit) -->",
        "<!-- BENCH_TABLE:END -->",
        build_bench_table(index_compare),
    )
    text = _replace_block(
        text,
        "<!-- METRICS_TABLE:BEGIN (autogenerated by eval/emit_readme_tables.py — do not hand-edit) -->",
        "<!-- METRICS_TABLE:END -->",
        build_metrics_table(e2e, parser),
    )
    return text


def main(argv=None) -> None:
    p = argparse.ArgumentParser()
    p.add_argument("--results", type=str, default=str(RESULTS))
    p.add_argument("--readme", type=str, default=str(README))
    p.add_argument("--check", action="store_true")
    args = p.parse_args(argv)
    results_dir = Path(args.results)
    readme_path = Path(args.readme)
    current = readme_path.read_text()
    updated = generate(current, results_dir)
    if args.check:
        if current != updated:
            print("README benchmark blocks are STALE vs eval/results/*.json", file=sys.stderr)
            sys.exit(1)
        print("README benchmark blocks match results JSON")
        return
    readme_path.write_text(updated)
    print(f"Patched {readme_path}")


if __name__ == "__main__":
    main()
